static bool is_bad(int argc,char** argv) { return argc>1 && std::strcmp(argv[1],"--bad")==0; }

/*
案例 S09：GPUVA复用后的旧指针
真正错误原因：新旧裸指针地址相同时普通address-check可能无法识别旧epoch；复用不保证发生
NVIDIA 检测预期：unsupported；切勿将GPU Runtime错误或CPU ASan视为设备Sanitizer命中。
说明：--good 正常语义，--bad 故意触发；运行结果需通过GPU工具日志验证。
*/

__global__ void s09_reused(unsigned* p) {
    if(threadIdx.x==0) p[0]=91;
}

int main(int argc,char** argv) {
    bool bad=is_bad(argc,argv);
    unsigned *p=nullptr,*fresh=nullptr;
    GPU_CHECK(gpuMalloc((void**)&p,64));
    unsigned* old=p;
    GPU_CHECK(gpuFree(p));
    GPU_CHECK(gpuMalloc((void**)&fresh,64));
    if(bad && old!=fresh) {
        // 没有实现受控GPUVA复用的前提，不伪造一个“reuse UAF”。
        GPU_CHECK(gpuFree(fresh));
        std::puts("SKIP: GPUVA-not-reused");
        return 77;
    }
    s09_reused<<<1,32>>>(bad?old:fresh);
    GPU_CHECK(gpuDeviceSynchronize());
    GPU_CHECK(gpuFree(fresh)); return 0;
}

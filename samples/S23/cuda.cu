static bool is_bad(int argc,char** argv) { return argc>1 && std::strcmp(argv[1],"--bad")==0; }

/*
案例 S23：Constant空间符号尾部越界
GPU真实场景及错误原因：测试只读常量地址空间符号边界；不等同GPU纹理/surface坐标模式或写权限校验
本后端的GPU Sanitizer预期：conditional。若未检测到必须显示NOT_DETECTED/UNSUPPORTED。
--good使用合法对照；--bad触发错误或检查器边界。设备越界绝非CPU数组错误。
*/

__constant__ unsigned s23_const_table[4]={2,4,6,8};
__global__ void s23_read_constant(unsigned* out,int bad) {
    if(threadIdx.x==0) {
        // bad读取const_table[4]；有的后端会优化或缺少constant访问检测。
        out[0]=s23_const_table[bad?4:3];
    }
}

int main(int argc,char** argv) {
    unsigned* out=nullptr; GPU_CHECK(gpuMalloc((void**)&out,sizeof(unsigned)));
    s23_read_constant<<<1,32>>>(out,is_bad(argc,argv));
    GPU_CHECK(gpuDeviceSynchronize()); GPU_CHECK(gpuFree(out)); return 0;
}

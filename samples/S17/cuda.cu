static bool is_bad(int argc,char** argv) { return argc>1 && std::strcmp(argv[1],"--bad")==0; }

/*
案例 S17：Block barrier缺失参与者
GPU真实场景及错误原因：错误线程参与集合可能死锁，必须--allow-dangerous且有限时运行；AMD ASan不是synccheck
本后端的GPU Sanitizer预期：conditional。若未检测到必须显示NOT_DETECTED/UNSUPPORTED。
--good使用合法对照；--bad触发错误或检查器边界。设备越界绝非CPU数组错误。
*/

__global__ void s17_block_barrier(unsigned* out,int bad) {
    // good: 同一block的所有线程均参与。bad: 只有半数线程参与。
    if(!bad || threadIdx.x<16) __syncthreads();
    if(threadIdx.x==0) out[0]=7;
}

int main(int argc,char** argv) {
    unsigned* out=nullptr; GPU_CHECK(gpuMalloc((void**)&out,sizeof(unsigned)));
    s17_block_barrier<<<1,32>>>(out,is_bad(argc,argv));
    // 坏例可能导致设备或队列阻塞，必须使用外部40秒timeout。
    GPU_CHECK(gpuDeviceSynchronize()); GPU_CHECK(gpuFree(out)); return 0;
}
